#!/usr/bin/env python3
"""
Generates (or checks) Orbitersdk/Space Shuttle Vessel/OV/CabinLightingData.h

The header has, for each panel mesh of the virtual cockpit, the lighting channel of the panel (which PANEL knob of the cabin lighting
dims it) and the materials of the mesh that the panel lighting dims (the surfaces of the panel, not the lamps, displays and glass).
The material names come from the meshes, so the table must be generated again when a panel mesh changes: the check mode (--check, used by
tools/check-data.py) reports a table that does not agree with the meshes.

usage: gen-cabin-lighting-data.py [--check] [repo root]
"""
import glob
import os
import sys

# the materials that are lit by the panel lighting (the others are lamps, displays, glass or invisible)
DIMMABLE = {'panels', 'guards', 'switches', 'rotaryswitches', 'levers', 'circuitbreakers', 'plastic', 'russianpanels', 'russianswitches', 'pushbuttons', 'russianpushbuttons'}

# lighting channels: the PANEL knobs of the cabin lighting
CH_NONE, CH_LEFT_CTR, CH_LEFT_OVHD, CH_RIGHT_CTR, CH_RIGHT_OVHD, CH_MS, CH_OS = range(7)
CH_NAMES = ['NONE', 'LEFT_CTR', 'LEFT_OVHD', 'RIGHT_CTR', 'RIGHT_OVHD', 'MS', 'OS']

CHANNEL = {}
for n in ('F2', 'F3', 'F4', 'F6', 'F7', 'C2', 'C3', 'L1', 'L2', 'L4', 'L9', 'L10_IUS', 'L12U_SSP_Centaur', 'L12U_SSP_IUS'):
    CHANNEL[n] = CH_LEFT_CTR
for n in ('F8', 'F9', 'R1', 'R2', 'R4'):
    CHANNEL[n] = CH_RIGHT_CTR
for n in ('O1', 'O2', 'O3', 'O5', 'O6', 'O7'):
    CHANNEL[n] = CH_LEFT_OVHD
for n in ('O8', 'O9', 'O13', 'O14', 'O15', 'O16', 'O17'):
    CHANNEL[n] = CH_RIGHT_OVHD
for n in ('R10', 'R13L', 'R13U', 'R14'):
    CHANNEL[n] = CH_MS
for n in ('A1U', 'A1L', 'A1R', 'A2', 'A3', 'A4', 'A6U', 'A7U', 'A7A3_ISS', 'A7A3_SPDS', 'A8A1', 'A8A2', 'A8A3', 'A12A1', 'A12A2', 'A134'):
    CHANNEL[n] = CH_OS


def materials_of(path):
    text = open(path, 'rb').read().decode('latin-1').replace('\r\n', '\n').split('\n')
    for i, line in enumerate(text):
        if line.startswith('MATERIALS'):
            n = int(line.split()[1])
            return [text[i + 1 + k].strip() for k in range(n)]
    return []


def build(root):
    rows = []
    for path in sorted(glob.glob(os.path.join(root, 'Meshes', 'SSV', 'OV', 'panel*.msh')), key=lambda p: os.path.basename(p).lower()):
        base = os.path.basename(path)[:-4]
        name = base[5:]
        mats = materials_of(path)
        mask = 0
        for i, m in enumerate(mats):
            if m.lower() in DIMMABLE:
                mask |= 1 << i
        rows.append((base.lower(), CHANNEL.get(name, CH_NONE), mask, len(mats)))
    return rows


def render(rows):
    out = []
    out.append('// Generated by tools/gen-cabin-lighting-data.py: do not edit (run the script again when a panel mesh changes).')
    out.append('// For each panel mesh: the channel of the panel lighting and the materials that it dims (bit n = material n).')
    out.append('#ifndef _CABINLIGHTINGDATA_H_')
    out.append('#define _CABINLIGHTINGDATA_H_')
    out.append('')
    out.append('')
    out.append('namespace cabinlight')
    out.append('{')
    out.append('\tenum PanelChannel {PNL_NONE = 0, PNL_LEFT_CTR, PNL_LEFT_OVHD, PNL_RIGHT_CTR, PNL_RIGHT_OVHD, PNL_MS, PNL_OS, PNL_COUNT};')
    out.append('')
    out.append('\tstruct PanelLightingEntry')
    out.append('\t{')
    out.append('\t\tconst char* mesh;// name of the mesh file, without the folder and the extension, lower case')
    out.append('\t\tint channel;')
    out.append('\t\tunsigned long dimMask;')
    out.append('\t};')
    out.append('')
    out.append('\tinline constexpr PanelLightingEntry PANEL_LIGHTING[] = {')
    for base, ch, mask, n in rows:
        out.append('\t\t{"%s", PNL_%s, 0x%x},' % (base, CH_NAMES[ch], mask))
    out.append('\t};')
    out.append('\tinline constexpr int PANEL_LIGHTING_COUNT = sizeof( PANEL_LIGHTING ) / sizeof( PANEL_LIGHTING[0] );')
    out.append('}')
    out.append('')
    out.append('')
    out.append('#endif// _CABINLIGHTINGDATA_H_')
    out.append('')
    return '\n'.join(out)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv
    root = args[0] if args else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target = os.path.join(root, 'Orbitersdk', 'Space Shuttle Vessel', 'OV', 'CabinLightingData.h')
    text = render(build(root))
    if check:
        have = open(target, 'rb').read().decode('latin-1').replace('\r\n', '\n') if os.path.exists(target) else ''
        if have != text:
            print('ERROR: %s does not agree with the panel meshes: run tools/gen-cabin-lighting-data.py' % os.path.relpath(target, root))
            return 1
        print('cabin lighting data: ok')
        return 0
    open(target, 'wb').write(text.encode('latin-1'))
    print('written', target)
    return 0


if __name__ == '__main__':
    sys.exit(main())
